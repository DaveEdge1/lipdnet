// Generate NOAA controlled-vocabulary lists for the advanced-search autocompletes
// from NCEI's live params.json, into src/lib/noaaVocab.generated.ts.
//
// The NCEI paleo-search "params" endpoint publishes every controlled value the
// search API accepts, scoped by archive type. We flatten it to distinct term
// lists that back <datalist> autocompletes on the NOAA import filters, so a typo
// no longer silently returns zero results.
//
//   Variable  -> cvWhats       (leaf of the PaST "what" hierarchy)
//   Material  -> cvMaterials   (leaf of the material hierarchy)
//   Seasonality -> cvSeasonalities (NOAA's own vocab, kept whole)
//   Location  -> locations     (full "Continent>..." hierarchy)
//
// NCEI substring-matches these params, so the human-readable leaf is a valid
// query value (verified: cvWhats="surface temperature" and cvMaterials="wood"
// both return studies).
//
// Refresh:  node scripts/generate-noaa-vocab.mjs
// (fetches NCEI live; pass a local params.json path as argv[2] to work offline.)

import { writeFileSync, readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const PARAMS_URL = 'https://www.ncei.noaa.gov/access/paleo-search/study/params.json'
const here = dirname(fileURLToPath(import.meta.url))
const OUT = join(here, '..', 'src', 'lib', 'noaaVocab.generated.ts')

const leaf = (s) => String(s).split('>').pop().trim()
const clean = (arr) => [...new Set(arr.map(x => String(x).trim()).filter(Boolean))]
  .sort((a, b) => a.localeCompare(b))

async function loadParams() {
  const local = process.argv[2]
  if (local) return JSON.parse(readFileSync(local, 'utf8'))
  const res = await fetch(PARAMS_URL)
  if (!res.ok) throw new Error(`NCEI params.json fetch failed: HTTP ${res.status}`)
  return res.json()
}

const params = await loadParams()
const cv = params?.cvValues?.NOAA ?? {}

const whats = [], materials = [], seasonalities = []
for (const groups of Object.values(cv)) {
  for (const grp of groups) {
    for (const w of grp.cvWhats ?? []) {
      if (w.what) whats.push(leaf(w.what))
      ;(w.materials ?? []).forEach(m => materials.push(leaf(m)))
      ;(w.seasonalities ?? []).forEach(s => seasonalities.push(s)) // keep whole
    }
  }
}

// locations.NOAA is keyed by dataTypeId -> array of "Continent>..." strings
const locations = []
const walkLoc = (v) => {
  if (Array.isArray(v)) v.forEach(walkLoc)
  else if (v && typeof v === 'object') Object.values(v).forEach(walkLoc)
  else if (typeof v === 'string') locations.push(v)
}
walkLoc(params?.locations?.NOAA ?? {})

const WHATS = clean(whats)
const MATERIALS = clean(materials)
const SEASONALITIES = clean(seasonalities)
const LOCATIONS = clean(locations)

const arr = (name, xs) =>
  `export const ${name}: readonly string[] = [\n` +
  xs.map(x => `  ${JSON.stringify(x)},`).join('\n') +
  `\n]\n`

const body =
  `// AUTO-GENERATED by scripts/generate-noaa-vocab.mjs — do not edit by hand.\n` +
  `// NOAA NCEI controlled vocabulary for the advanced-search autocompletes.\n` +
  `// Source: ${PARAMS_URL}\n\n` +
  arr('NOAA_CV_WHATS', WHATS) + '\n' +
  arr('NOAA_CV_MATERIALS', MATERIALS) + '\n' +
  arr('NOAA_CV_SEASONALITIES', SEASONALITIES) + '\n' +
  arr('NOAA_LOCATIONS', LOCATIONS)

writeFileSync(OUT, body)
console.log(`Wrote ${OUT}`)
console.log(`  cvWhats leaves:      ${WHATS.length}`)
console.log(`  cvMaterials leaves:  ${MATERIALS.length}`)
console.log(`  cvSeasonalities:     ${SEASONALITIES.length}`)
console.log(`  locations:           ${LOCATIONS.length}`)
console.log(`  generated size:      ${(body.length / 1024).toFixed(0)}KB`)
