/**
 * Statistics tracking module for LiPD Playground
 * Tracks uploads and downloads with persistence to a JSON file
 */

var fs = require('fs');
var path = require('path');
var logger = require('./node_log.js');

// Path to the stats file (in logs directory for container volume persistence)
var STATS_FILE = path.join(process.cwd(), 'logs', 'playground_stats.json');

/**
 * Default stats structure
 */
var defaultStats = {
    uploads: {
        lipd: { total: 0, history: [] },
        noaa: { total: 0, history: [] },
        lipdverse: { total: 0, history: [] },
        wiki: { total: 0, history: [] }
    },
    downloads: {
        lipd: { total: 0, history: [] },
        noaa: { total: 0, history: [] }
    },
    lastUpdated: null,
    startedTracking: null
};

/**
 * Load stats from file, or create default if not exists
 */
var loadStats = function() {
    try {
        if (fs.existsSync(STATS_FILE)) {
            var data = fs.readFileSync(STATS_FILE, 'utf8');
            var stats = JSON.parse(data);
            logger.info('node_stats: Loaded stats from file');
            return stats;
        }
    } catch (err) {
        logger.info('node_stats: Error loading stats file, using defaults: ' + err);
    }

    // Return default stats with tracking start time
    var stats = JSON.parse(JSON.stringify(defaultStats));
    stats.startedTracking = new Date().toISOString();
    return stats;
};

/**
 * Save stats to file
 */
var saveStats = function(stats) {
    try {
        stats.lastUpdated = new Date().toISOString();
        fs.writeFileSync(STATS_FILE, JSON.stringify(stats, null, 2));
        logger.info('node_stats: Stats saved to file');
    } catch (err) {
        logger.info('node_stats: Error saving stats file: ' + err);
    }
};

// In-memory stats cache
var stats = loadStats();

/**
 * Record an upload event
 * @param {String} type - Type of upload: 'lipd', 'noaa', 'lipdverse', 'wiki'
 * @param {Object} metadata - Optional metadata about the upload (filename, etc)
 */
var recordUpload = function(type, metadata) {
    try {
        if (!stats.uploads[type]) {
            logger.info('node_stats: Unknown upload type: ' + type);
            return;
        }

        stats.uploads[type].total++;

        var entry = {
            timestamp: new Date().toISOString(),
            metadata: metadata || {}
        };

        // Keep only last 1000 entries to prevent file from growing too large
        stats.uploads[type].history.push(entry);
        if (stats.uploads[type].history.length > 1000) {
            stats.uploads[type].history = stats.uploads[type].history.slice(-1000);
        }

        saveStats(stats);
        logger.info('node_stats: Recorded ' + type + ' upload. Total: ' + stats.uploads[type].total);
    } catch (err) {
        logger.info('node_stats: Error recording upload: ' + err);
    }
};

/**
 * Record a download event
 * @param {String} type - Type of download: 'lipd', 'noaa'
 * @param {Object} metadata - Optional metadata about the download (filename, etc)
 */
var recordDownload = function(type, metadata) {
    try {
        if (!stats.downloads[type]) {
            logger.info('node_stats: Unknown download type: ' + type);
            return;
        }

        stats.downloads[type].total++;

        var entry = {
            timestamp: new Date().toISOString(),
            metadata: metadata || {}
        };

        // Keep only last 1000 entries to prevent file from growing too large
        stats.downloads[type].history.push(entry);
        if (stats.downloads[type].history.length > 1000) {
            stats.downloads[type].history = stats.downloads[type].history.slice(-1000);
        }

        saveStats(stats);
        logger.info('node_stats: Recorded ' + type + ' download. Total: ' + stats.downloads[type].total);
    } catch (err) {
        logger.info('node_stats: Error recording download: ' + err);
    }
};

/**
 * Get current stats
 * @param {Boolean} includeHistory - Whether to include full history arrays
 * @returns {Object} Current statistics
 */
var getStats = function(includeHistory) {
    // Reload from file to ensure we have latest data
    stats = loadStats();

    if (includeHistory) {
        return stats;
    }

    // Return summary without history arrays
    return {
        uploads: {
            lipd: { total: stats.uploads.lipd.total, recentCount: getRecentCount(stats.uploads.lipd.history, 24) },
            noaa: { total: stats.uploads.noaa.total, recentCount: getRecentCount(stats.uploads.noaa.history, 24) },
            lipdverse: { total: stats.uploads.lipdverse.total, recentCount: getRecentCount(stats.uploads.lipdverse.history, 24) },
            wiki: { total: stats.uploads.wiki.total, recentCount: getRecentCount(stats.uploads.wiki.history, 24) }
        },
        downloads: {
            lipd: { total: stats.downloads.lipd.total, recentCount: getRecentCount(stats.downloads.lipd.history, 24) },
            noaa: { total: stats.downloads.noaa.total, recentCount: getRecentCount(stats.downloads.noaa.history, 24) }
        },
        totals: {
            uploads: stats.uploads.lipd.total + stats.uploads.noaa.total + stats.uploads.lipdverse.total + stats.uploads.wiki.total,
            downloads: stats.downloads.lipd.total + stats.downloads.noaa.total
        },
        lastUpdated: stats.lastUpdated,
        startedTracking: stats.startedTracking
    };
};

/**
 * Get count of entries from the last N hours
 * @param {Array} history - Array of history entries
 * @param {Number} hours - Number of hours to look back
 * @returns {Number} Count of entries in the time period
 */
var getRecentCount = function(history, hours) {
    var cutoff = new Date();
    cutoff.setHours(cutoff.getHours() - hours);

    var count = 0;
    for (var i = history.length - 1; i >= 0; i--) {
        var entryDate = new Date(history[i].timestamp);
        if (entryDate >= cutoff) {
            count++;
        } else {
            break; // History is chronological, so we can stop early
        }
    }
    return count;
};

/**
 * Get stats for a specific time period
 * @param {String} period - 'hour', 'day', 'week', 'month', 'all'
 * @returns {Object} Statistics for the period
 */
var getStatsByPeriod = function(period) {
    stats = loadStats();

    var hours;
    switch (period) {
        case 'hour': hours = 1; break;
        case 'day': hours = 24; break;
        case 'week': hours = 168; break;
        case 'month': hours = 720; break;
        case 'all':
        default:
            return getStats(false);
    }

    return {
        period: period,
        uploads: {
            lipd: getRecentCount(stats.uploads.lipd.history, hours),
            noaa: getRecentCount(stats.uploads.noaa.history, hours),
            lipdverse: getRecentCount(stats.uploads.lipdverse.history, hours),
            wiki: getRecentCount(stats.uploads.wiki.history, hours)
        },
        downloads: {
            lipd: getRecentCount(stats.downloads.lipd.history, hours),
            noaa: getRecentCount(stats.downloads.noaa.history, hours)
        }
    };
};

/**
 * Reset all stats (for testing/admin purposes)
 */
var resetStats = function() {
    stats = JSON.parse(JSON.stringify(defaultStats));
    stats.startedTracking = new Date().toISOString();
    saveStats(stats);
    logger.info('node_stats: Stats reset');
    return stats;
};

module.exports = {
    recordUpload: recordUpload,
    recordDownload: recordDownload,
    getStats: getStats,
    getStatsByPeriod: getStatsByPeriod,
    resetStats: resetStats
};
