/**
 * Statistics tracking module for LiPD Playground
 * Tracks uploads and downloads with persistence to a JSON file
 */

var fs = require('fs');
var path = require('path');
var logger = require('./node_log.js');

// Path to the stats file (in logs directory for container volume persistence)
var STATS_FILE = path.join(process.cwd(), 'logs', 'playground_stats.json');

/**
 * Default stats structure
 */
var defaultStats = {
    pageVisits: {
        playground: { total: 0, history: [] },
        query: { total: 0, history: [] },
        merge: { total: 0, history: [] },
        home: { total: 0, history: [] }
    },
    uploads: {
        lipd: { total: 0, history: [] },
        noaa: { total: 0, history: [] },
        lipdverse: { total: 0, history: [] },
        wiki: { total: 0, history: [] }
    },
    downloads: {
        lipd: { total: 0, history: [] },
        noaa: { total: 0, history: [] }
    },
    uniqueUsers: {
        // Stores { ip: lastSeenTimestamp } for tracking unique visitors
        all: {},
        // History of unique user visits for time-based queries
        history: []
    },
    lastUpdated: null,
    startedTracking: null
};

/**
 * Load stats from file, or create default if not exists
 */
var loadStats = function() {
    try {
        if (fs.existsSync(STATS_FILE)) {
            var data = fs.readFileSync(STATS_FILE, 'utf8');
            var stats = JSON.parse(data);
            logger.info('node_stats: Loaded stats from file');
            return stats;
        }
    } catch (err) {
        logger.info('node_stats: Error loading stats file, using defaults: ' + err);
    }

    // Return default stats with tracking start time
    var stats = JSON.parse(JSON.stringify(defaultStats));
    stats.startedTracking = new Date().toISOString();
    return stats;
};

/**
 * Save stats to file
 */
var saveStats = function(stats) {
    try {
        stats.lastUpdated = new Date().toISOString();
        fs.writeFileSync(STATS_FILE, JSON.stringify(stats, null, 2));
        logger.info('node_stats: Stats saved to file');
    } catch (err) {
        logger.info('node_stats: Error saving stats file: ' + err);
    }
};

// In-memory stats cache
var stats = loadStats();

/**
 * Record a unique user visit by IP address
 * @param {String} ip - User's IP address
 */
var recordUniqueUser = function(ip) {
    if (!ip) return;

    try {
        // Initialize uniqueUsers if not exists (backwards compatibility)
        if (!stats.uniqueUsers) {
            stats.uniqueUsers = { all: {}, history: [] };
        }

        var now = new Date().toISOString();
        var isNewUser = !stats.uniqueUsers.all[ip];

        // Update last seen timestamp
        stats.uniqueUsers.all[ip] = now;

        // Record in history for time-based queries
        stats.uniqueUsers.history.push({
            timestamp: now,
            ip: ip,
            isNew: isNewUser
        });

        // Keep only last 10000 entries to prevent file from growing too large
        if (stats.uniqueUsers.history.length > 10000) {
            stats.uniqueUsers.history = stats.uniqueUsers.history.slice(-10000);
        }

        if (isNewUser) {
            logger.info('node_stats: New unique user recorded. Total unique: ' + Object.keys(stats.uniqueUsers.all).length);
        }
    } catch (err) {
        logger.info('node_stats: Error recording unique user: ' + err);
    }
};

/**
 * Get unique user count for a time period
 * @param {Number} hours - Number of hours to look back (0 for all time)
 * @returns {Number} Count of unique users in the period
 */
var getUniqueUserCount = function(hours) {
    if (!stats.uniqueUsers) return 0;

    if (!hours || hours <= 0) {
        // Return total unique users
        return Object.keys(stats.uniqueUsers.all).length;
    }

    // Count unique IPs in the time period
    var cutoff = new Date();
    cutoff.setHours(cutoff.getHours() - hours);

    var uniqueIps = {};
    for (var i = stats.uniqueUsers.history.length - 1; i >= 0; i--) {
        var entry = stats.uniqueUsers.history[i];
        var entryDate = new Date(entry.timestamp);
        if (entryDate >= cutoff) {
            uniqueIps[entry.ip] = true;
        } else {
            break; // History is chronological
        }
    }
    return Object.keys(uniqueIps).length;
};

/**
 * Record an upload event
 * @param {String} type - Type of upload: 'lipd', 'noaa', 'lipdverse', 'wiki'
 * @param {Object} metadata - Optional metadata about the upload (filename, etc)
 * @param {String} userIp - Optional user IP for unique user tracking
 */
var recordUpload = function(type, metadata, userIp) {
    try {
        if (!stats.uploads[type]) {
            logger.info('node_stats: Unknown upload type: ' + type);
            return;
        }

        stats.uploads[type].total++;

        var entry = {
            timestamp: new Date().toISOString(),
            metadata: metadata || {}
        };

        // Keep only last 1000 entries to prevent file from growing too large
        stats.uploads[type].history.push(entry);
        if (stats.uploads[type].history.length > 1000) {
            stats.uploads[type].history = stats.uploads[type].history.slice(-1000);
        }

        // Track unique user
        if (userIp) {
            recordUniqueUser(userIp);
        }

        saveStats(stats);
        logger.info('node_stats: Recorded ' + type + ' upload. Total: ' + stats.uploads[type].total);
    } catch (err) {
        logger.info('node_stats: Error recording upload: ' + err);
    }
};

